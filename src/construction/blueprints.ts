export const INITIAL_HOLD = 1.25;
export const stageDuration = (reduced: boolean) => (reduced ? 0.32 : 1.55);
export function constructionAt(lab: LabId, elapsed: number, reduced: boolean) {
  const count = BLUEPRINTS[lab].length,
    duration = stageDuration(reduced);
  const progress = Math.max(0, (elapsed - INITIAL_HOLD) / duration);
  const introduced =
    elapsed < INITIAL_HOLD ? 0 : Math.min(count, Math.floor(progress) + 1);
  const attached = Math.min(count, Math.floor(progress));
  return {
    introduced,
    attached,
    active: Math.min(count - 1, Math.floor(progress)),
    fraction: progress - Math.floor(progress),
    complete: attached === count,
  };
}
