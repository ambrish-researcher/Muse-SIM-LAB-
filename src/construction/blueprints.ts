import type { LabId } from "../simulation";
export type Vector = [number, number, number];
export type ConstructionPart = {
  id: string;
  name: string;
  purpose: string;
  principle: string;
  relationship: string;
  parent?: string;
  target: Vector;
  classification: string;
  levels: { beginner: string; engineering: string; research: string };
};
type Spec = [string, string, string, string, Vector, string?];
function blueprint(lab: LabId, specs: Spec[]): ConstructionPart[] {
  return specs.map(([id, name, purpose, principle, target, parent]) => ({
    id,
    name,
    purpose,
    principle,
    target,
    parent,
    relationship: parent
      ? `Attaches to ${specs.find((p) => p[0] === parent)![1]}. ${
          specs.some((p) => p[5] === id)
            ? `Dependent components: ${specs
                .filter((p) => p[5] === id)
                .map((p) => p[1])
                .join(", ")}.`
            : "The local coordinate frame preserves its relationship to the parent structure."
        }`
      : "Root component: establishes the coordinate frame for every attached subsystem.",
    classification:
      lab === "wonder"
        ? "Conceptual AI architecture · real toy calculations"
        : lab === "chip"
          ? "Independent package reconstruction · illustrative topology"
          : "Conceptual humanoid · executable kinematic model",
    levels: {
      beginner: `${purpose} ${principle}`,
      engineering: `${principle} ${parent ? `The assembly registers this part against ${specs.find((p) => p[0] === parent)![1]}; its local frame stays attached during inspection.` : "All downstream coordinates are expressed relative to this root."} ${lab === "robot" ? "Joint motion is kinematic; no torque or contact dynamics are claimed." : lab === "chip" ? "The visible arrangement is explanatory, not a manufacturer floorplan." : "Tensors in the experiment are computed locally from fixed, untrained weights."}`,
      research: `${principle} ${lab === "wonder" ? "This four-dimensional, two-head example tests the mathematical mechanism, not the capacity, training data or hidden design of Muse Wonder. Active Memory and Active Focus are independent teaching models." : lab === "chip" ? "Browser MAC counts and quantization errors are measurable; device throughput, energy and proprietary topology are not inferred from this model. Package geometry and software layers are conceptual." : "A* operates on an eight-by-eight occupancy grid. FABRIK solves a two-link chain; successful endpoint and object-state checks do not establish dynamic balance or real-world grasp robustness."}`,
    },
  }));
}
